-- =====================================================
-- 1. USERS
-- =====================================================

CREATE TABLE users
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(30)  NOT NULL UNIQUE,
    email    VARCHAR(50)  NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role     VARCHAR(20),
    active   BOOLEAN      NOT NULL
);


-- =====================================================
-- 2. PRODUCTS
-- =====================================================

CREATE TABLE products
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    internal_code    VARCHAR(60)  NOT NULL UNIQUE,
    name             VARCHAR(150) NOT NULL,
    category         VARCHAR(80),
    presentation     VARCHAR(80),
    measure_unit     VARCHAR(40),
    days_useful_life INTEGER,
    active           BOOLEAN      NOT NULL,

    CONSTRAINT chk_products_useful_life
        CHECK (days_useful_life IS NULL OR days_useful_life >= 0)
);


-- =====================================================
-- 3. LOCATIONS
-- =====================================================

CREATE TABLE locations
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_code VARCHAR(60)  NOT NULL UNIQUE,
    name          VARCHAR(150) NOT NULL,
    address       VARCHAR(250),
    latitude      NUMERIC(10, 7),
    longitude     NUMERIC(10, 7),
    responsible   VARCHAR(120),
    type          SMALLINT,
    active        BOOLEAN      NOT NULL
);


-- =====================================================
-- 4. PRODUCTION ORDERS
-- =====================================================

CREATE TABLE production_orders
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id        BIGINT         NOT NULL,
    user_id           BIGINT         NOT NULL,
    order_code        VARCHAR(60)    NOT NULL UNIQUE,
    planned_quantity  NUMERIC(14, 3) NOT NULL,
    produced_quantity NUMERIC(14, 3) NOT NULL,
    production_date   TIMESTAMP,

    CONSTRAINT fk_production_orders_product
        FOREIGN KEY (product_id) REFERENCES products (id),

    CONSTRAINT fk_production_orders_user
        FOREIGN KEY (user_id) REFERENCES users (id),

    CONSTRAINT chk_planned_quantity
        CHECK (planned_quantity >= 0),

    CONSTRAINT chk_produced_quantity
        CHECK (produced_quantity >= 0)
);


-- =====================================================
-- 5. BATCHS
-- =====================================================

CREATE TABLE batchs
(
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          BIGINT         NOT NULL,
    production_order_id BIGINT,
    batch_code          VARCHAR(60)    NOT NULL UNIQUE,
    initial_quantity    NUMERIC(14, 3) NOT NULL,
    manufacture_date    TIMESTAMP,
    expiration_date     TIMESTAMP,
    quality_status      SMALLINT,

    CONSTRAINT fk_batchs_product
        FOREIGN KEY (product_id) REFERENCES products (id),

    CONSTRAINT fk_batchs_production_order
        FOREIGN KEY (production_order_id) REFERENCES production_orders (id),

    CONSTRAINT chk_batch_initial_quantity
        CHECK (initial_quantity >= 0)
);


-- =====================================================
-- 6. DETAIL DISPATCH
-- =====================================================

CREATE TABLE detail_dispatch
(
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispatch_code              VARCHAR(60) NOT NULL UNIQUE,
    origin_headquarter_id      BIGINT      NOT NULL,
    destination_headquarter_id BIGINT      NOT NULL,
    departure_date             TIMESTAMP,
    estimated_arrival_date     TIMESTAMP,
    reception_date             TIMESTAMP,
    status                     SMALLINT    NOT NULL,
    is_replacement             BOOLEAN     NOT NULL,

    CONSTRAINT fk_dispatch_origin
        FOREIGN KEY (origin_headquarter_id) REFERENCES locations (id),

    CONSTRAINT fk_dispatch_destination
        FOREIGN KEY (destination_headquarter_id) REFERENCES locations (id)
);


-- =====================================================
-- 7. INVENTORY MOVEMENTS
-- =====================================================

CREATE TABLE inventory_movements
(
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                  BIGINT         NOT NULL,
    batch_id                 BIGINT         NOT NULL,
    origin_warehouse_id      BIGINT,
    destination_warehouse_id BIGINT,
    type                     SMALLINT       NOT NULL,
    quantity                 NUMERIC(14, 3) NOT NULL,
    reference_id             BIGINT,
    date                     TIMESTAMP      NOT NULL,

    CONSTRAINT fk_inventory_user
        FOREIGN KEY (user_id) REFERENCES users (id),

    CONSTRAINT fk_inventory_batch
        FOREIGN KEY (batch_id) REFERENCES batchs (id),

    CONSTRAINT fk_inventory_origin
        FOREIGN KEY (origin_warehouse_id) REFERENCES locations (id),

    CONSTRAINT fk_inventory_destination
        FOREIGN KEY (destination_warehouse_id) REFERENCES locations (id)
);


-- =====================================================
-- 8. HEADQUARTERS INVENTORY
-- =====================================================

CREATE TABLE headquarters_inventory
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id       BIGINT         NOT NULL,
    batch_id           BIGINT         NOT NULL,
    available_quantity NUMERIC(14, 3) NOT NULL,
    withheld_quantity  NUMERIC(14, 3) NOT NULL,
    update_date        TIMESTAMP      NOT NULL,

    CONSTRAINT fk_headquarters_inventory_warehouse
        FOREIGN KEY (warehouse_id) REFERENCES locations (id),

    CONSTRAINT fk_headquarters_inventory_batch
        FOREIGN KEY (batch_id) REFERENCES batchs (id),

    CONSTRAINT chk_available_quantity
        CHECK (available_quantity >= 0),

    CONSTRAINT chk_withheld_quantity
        CHECK (withheld_quantity >= 0)
);


-- =====================================================
-- 9. QUALITY INSPECTION
-- =====================================================

CREATE TABLE quality_inspection
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id        BIGINT      NOT NULL,
    user_id         BIGINT      NOT NULL,
    inspection_date TIMESTAMP   NOT NULL,
    result          VARCHAR(50) NOT NULL,
    observations    VARCHAR(1000),
    url_evidence    VARCHAR(500),

    CONSTRAINT fk_quality_inspection_batch
        FOREIGN KEY (batch_id) REFERENCES batchs (id),

    CONSTRAINT fk_quality_inspection_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);


-- =====================================================
-- 10. REPLACEMENT CLAIMS
-- =====================================================

CREATE TABLE replacement_claims
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    claim_code         VARCHAR(60)    NOT NULL UNIQUE,
    dispatch_id        BIGINT,
    batch_id           BIGINT         NOT NULL,
    headquarter_id     BIGINT         NOT NULL,
    incident_type      VARCHAR(80)    NOT NULL,
    affected_quantity  NUMERIC(14, 3) NOT NULL,
    status             VARCHAR(50)    NOT NULL,
    authorized_by      VARCHAR(120),
    authorization_date TIMESTAMP,

    CONSTRAINT fk_replacement_claims_dispatch
        FOREIGN KEY (dispatch_id) REFERENCES detail_dispatch (id),

    CONSTRAINT fk_replacement_claims_batch
        FOREIGN KEY (batch_id) REFERENCES batchs (id),

    CONSTRAINT fk_replacement_claims_headquarter
        FOREIGN KEY (headquarter_id) REFERENCES locations (id),

    CONSTRAINT chk_affected_quantity
        CHECK (affected_quantity > 0)
);
